def read_input(path):
    """Load an explicit local regular file, rejecting links and remote inputs."""
    if re.match(r'^[A-Za-z][A-Za-z0-9+.-]*://', str(path)):
        raise ValueError('URL intake is not available here; use authorized Web intake or provide a downloaded source file/ZIP.')
    descriptor = os.open(path, os.O_RDONLY | getattr(os, 'O_NOFOLLOW', 0) | getattr(os, 'O_NONBLOCK', 0))
    try:
        metadata = os.fstat(descriptor)
        if not stat.S_ISREG(metadata.st_mode):
            raise ValueError('Input must be a regular file (not a directory, link, or device).')
        if metadata.st_size > MAX_INPUT:
            raise ValueError('Input exceeds 5 MiB limit.')
        with os.fdopen(descriptor, 'rb', closefd=False) as source:
            data = source.read(MAX_INPUT + 1)
        return read_package(data, str(path))
    finally:
        os.close(descriptor)


def render_text(report):
    """Concise evidence-first rendering; JSON retains the complete bounded schema."""
    lines = [f"SOURCE AUDIT: {report['recommendation']['verdict'].upper()}",
             f"Coverage: {report['coverage']['inspected_files']}/{report['coverage']['total_files']} files, {report['coverage']['total_bytes']} bytes"]
    for item in report['inventory'][:20]:
        lines.append(f"File: {item['path']} ({item['kind']}, {item['bytes']} bytes, SHA-256 {item['sha256']})")
    for item in report['capabilities'][:30]:
        lines.append(f"Capability [{item['category']}]: {item['label']}")
        for evidence in item['evidence'][:3]:
            lines.append(f"  {evidence['path']}:{evidence['line']} {evidence['symbol']} — {evidence['detail']}")
    for item in report['dependencies'][:30]:
        lines.append(f"Dependency: {item['name']} {item['version']} ({item['ecosystem']}; pinned={item['pinned']}) at {item['path']}:{item['line']}")
    for item in report['entrypoints'][:20]:
        lines.append(f"Entrypoint: {item['name']} ({item['kind']}) at {item['path']}:{item['line']}")
    for item in report['endpoints'][:20]:
        lines.append(f"External host: {item['host']} ({item['kind']}) at {item['path']}:{item['line']}")
    for item in report['licenses']:
        lines.append(f"License declaration: {item['identifier']} at {item['path']}")
    for item in report['indicators'][:30]:
        lines.append(f"Risk [{item['severity']}, {item['code']}] {item['path']}:{item['line']} — {item['detail']}")
    lines.extend('Conclusion: ' + reason for reason in report['recommendation']['reasons'])
    lines.extend(f"Coverage gap: {item['path']} — {item['reason']}" for item in report['coverage']['omitted'][:20])
    lines.extend(f"Check {item['name']}: {item['status']} — {item['detail']}" for item in report['checks'][:20])
    if any(len(report[k]) > n for k, n in [('inventory', 20), ('capabilities', 30), ('dependencies', 30), ('entrypoints', 20), ('endpoints', 20), ('indicators', 30), ('checks', 20)]) or len(report['coverage']['omitted']) > 20:
        lines.append('Text display is abbreviated; use --format json for all bounded evidence and coverage gaps.')
    return _clean('\n'.join(lines))


def main(argv=None):
    parser = argparse.ArgumentParser(description='Read-only source auditor: candidate code is never executed, imported, or installed. File/ZIP limits: 5 MiB input, 8 MiB expanded, 512 KiB/member, 512 members; accepted source members are inspected without a separate text cutoff. ZIP ratio max 100:1. No network requests.')
    parser.add_argument('path', help='Explicit local source file or ZIP; URLs require authorized Web intake.')
    parser.add_argument('--format', choices=('json', 'text'), default='text')
    args = parser.parse_args(argv)
    try:
        report = audit_files(read_input(args.path))
        print(json.dumps(report, ensure_ascii=True, indent=2) if args.format == 'json' else render_text(report))
        return 0
    except (OSError, ValueError) as exc:
        print('Source audit refused: ' + _clean(str(exc))[:300], file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
