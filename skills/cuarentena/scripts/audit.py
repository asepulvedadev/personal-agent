MAX_INPUT = 5 * 1024 * 1024
MAX_EXPANDED = 8 * 1024 * 1024
MAX_MEMBER = 512 * 1024
MAX_MEMBERS = 512
MAX_TEXT = MAX_MEMBER
MAX_RATIO = 100
MAX_RESULTS = 160
MAX_EVIDENCE = 8
URL = re.compile(r'https?://[^\s<>\[\]{}"\'`\\)]+', re.I)
SECRET_NAME = re.compile(r'(?:password|passwd|secret|(?:access|api|auth)[_-]?(?:key|token)|token|credential|private[_-]?key)', re.I)
TOKEN = re.compile(r'\b(?:gh[pousr]_[A-Za-z0-9_]{16,}|github_pat_[A-Za-z0-9_]{16,}|sk-[A-Za-z0-9_-]{16,}|AKIA[A-Z0-9]{16}|xox[baprs]-[A-Za-z0-9-]{12,}|[0-9]{7,}:[A-Za-z0-9_-]{25,})\b')
PRIVATE_KEY = re.compile(r'-----BEGIN [A-Z ]*PRIVATE KEY-----.*?(?:-----END [A-Z ]*PRIVATE KEY-----|\Z)', re.S)
CONTROL = re.compile(r'[\x00-\x08\x0b\x0c\x0e-\x1f\x7f-\x9f\u200b-\u200f\u202a-\u202e\u2066-\u2069\ufeff]')
ARCHIVE_SUFFIXES = ('.zip', '.tar', '.gz', '.tgz', '.bz2', '.xz', '.7z', '.rar', '.whl', '.jar')


def _clean(value, secrets=()):
    """Redact before clipping: clipping first could expose a credential fragment."""
    value = PRIVATE_KEY.sub('[REDACTED PRIVATE KEY]', str(value))
    for secret in sorted(set(secrets), key=len, reverse=True):
        if secret:
            if len(secret) < 8:
                value = re.sub(r'(?<![\w])' + re.escape(secret) + r'(?![\w])', '[REDACTED]', value)
            else:
                value = value.replace(secret, '[REDACTED]')
    value = TOKEN.sub('[REDACTED TOKEN]', value)
    value = re.sub(r'(https?://)[^/\s:@]+:[^/\s@]+@', r'\1[REDACTED]@', value, flags=re.I)
    value = re.sub(r'([?&](?:token|key|secret|password|access_token|api_key)=)[^\s&#"\']+', r'\1[REDACTED]', value, flags=re.I)
    value = re.sub(r'((?:password|passwd|secret|api[_-]?key|token)\s*[=:]\s*["\']?)[^\s,"\';)]+', r'\1[REDACTED]', value, flags=re.I)
    return CONTROL.sub('', value)


def clean_text(value):
    """Redact source-derived display text without interpreting its instructions."""
    text = str(value)
    audit = _Audit()
    _collect_secrets(audit, text)
    return _clean(text, audit.secrets)


def _sanitize_tree(value, secrets, parent=None):
    if isinstance(value, dict):
        result = {}
        for key, item in value.items():
            # Schema keys/enums/fingerprints are generated by us, never copied
            # from candidate objects. Redacting them would corrupt the contract
            # when a candidate credential happens to equal e.g. "path"/"high".
            fixed = key in ('category', 'severity', 'status', 'verdict', 'sha256')
            fixed = fixed or parent == 'checks' and key == 'name'
            result[key] = item if fixed else _sanitize_tree(item, secrets, key)
        return result
    if isinstance(value, list):
        return [_sanitize_tree(item, secrets, parent) for item in value]
    if isinstance(value, str):
        return _clean(value, secrets)[:600]
    return value


def _kind(path, data):
    name = PurePosixPath(path).name.lower()
    suffix = PurePosixPath(path).suffix.lower()
    if b'\0' in data[:8192]:
        return 'binary'
    if name == 'package.json':
        return 'npm_manifest'
    if name.startswith(('requirements', 'constraints')) and suffix == '.txt':
        return 'requirements'
    if suffix == '.toml':
        return 'toml'
    if suffix in ('.py', '.pyi'):
        return 'python'
    if suffix in ('.js', '.mjs', '.cjs', '.ts', '.tsx', '.jsx'):
        return 'javascript'
    if suffix in ('.sh', '.bash', '.zsh') or data.startswith(b'#!/bin/sh') or data.startswith(b'#!/bin/bash'):
        return 'shell'
    if name.startswith('dockerfile'):
        return 'docker'
    if suffix in ('.md', '.rst'):
        return 'documentation'
    if name.startswith(('license', 'copying')):
        return 'license'
    if suffix in ('.json', '.yml', '.yaml', '.ini', '.cfg', '.env') or name == 'makefile':
        return 'configuration'
    return 'text'


class _Audit:
    def __init__(self):
        self.result = {
            'version': 1,
            'coverage': {'total_files': 0, 'inspected_files': 0, 'total_bytes': 0, 'omitted': []},
            'inventory': [], 'capabilities': [], 'dependencies': [], 'entrypoints': [],
            'endpoints': [], 'licenses': [], 'indicators': [],
            'recommendation': {'verdict': 'review', 'reasons': []},
            'checks': [],
        }
        self.secrets = set()
        self.cap_index = {}
        self.endpoint_index = set()
        self.limit_keys = set()

    def add(self, key, item):
        if len(self.result[key]) < MAX_RESULTS:
            self.result[key].append(item)
        elif key not in self.limit_keys:
            self.limit_keys.add(key)
            self.omit('*', f'{key} results truncated at {MAX_RESULTS}')

    def omit(self, path, reason):
        omitted = self.result['coverage']['omitted']
        if len(omitted) < MAX_RESULTS:
            omitted.append({'path': path, 'reason': reason})
        elif omitted[-1]['path'] != '*':
            omitted[-1] = {'path': '*', 'reason': 'additional coverage omissions truncated'}

    def capability(self, category, label, path, line, symbol, detail):
        key = (category, label)
        evidence = {'path': path, 'line': line, 'symbol': symbol, 'detail': detail}
        if key not in self.cap_index:
            item = {'category': category, 'label': label, 'evidence': []}
            self.cap_index[key] = item
            self.add('capabilities', item)
        target = self.cap_index[key]['evidence']
        if len(target) < MAX_EVIDENCE:
            target.append(evidence)
        elif ('evidence', key) not in self.limit_keys:
            self.limit_keys.add(('evidence', key))
            self.omit(path, f'{category} evidence truncated at {MAX_EVIDENCE}')

    def indicator(self, code, category, severity, path, line, detail):
        self.add('indicators', dict(code=code, category=category, severity=severity,
                                    path=path, line=line, detail=detail))

    def endpoints(self, text, path, line, kind):
        matches = list(URL.finditer(text))
        if len(matches) > 16:
            self.omit(path, f'External endpoint evidence truncated at 16 matches on line {line}.')
        for match in matches[:16]:
            try:
                host = urlsplit(match.group()).hostname
            except ValueError:
                continue
            if not host:
                continue
            key = (host.lower(), path, line)
            if key not in self.endpoint_index and len(self.endpoint_index) < MAX_RESULTS:
                self.endpoint_index.add(key)
                self.add('endpoints', dict(host=host.lower(), path=path, line=line, kind=kind))
            elif key not in self.endpoint_index and 'endpoint_limit' not in self.limit_keys:
                self.limit_keys.add('endpoint_limit')
                self.omit(path, f'External endpoint results truncated at {MAX_RESULTS}.')

    def dependency(self, name, version, ecosystem, path, line):
        version = str(version)
        # Hash/URL references are intentionally not called pinned versions.
        pinned = bool(re.fullmatch(r'\d+(?:\.\d+){1,3}(?:[-+][\w.]+)?', version)
                      or re.fullmatch(r'==\d+(?:\.\d+){1,3}(?:[a-zA-Z0-9.+-]*)', version))
        self.add('dependencies', dict(name=str(name), version=version, ecosystem=ecosystem,
                                      path=path, line=line, pinned=pinned))

    def check(self, name, status, detail):
        self.add('checks', dict(name=name, status=status, detail=detail))

    def finish(self):
        coverage = self.result['coverage']
        high = [i for i in self.result['indicators'] if i['severity'] == 'high']
        indicators = self.result['indicators']
        if high:
            verdict = 'avoid'
            reasons = [f"{i['code']} at {i['path']}:{i['line']}: {i['detail']}" for i in high[:6]]
        elif coverage['omitted'] or indicators or not coverage['inspected_files']:
            verdict = 'review'
            reasons = [f"{i['code']} at {i['path']}:{i['line']}: {i['detail']}" for i in indicators[:5]]
            if coverage['omitted']:
                reasons.append('Coverage gaps require manual inspection; see coverage.omitted.')
            if not coverage['inspected_files']:
                reasons.append('No source text was inspected.')
        else:
            verdict = 'candidate'
            reasons = [f"Inspected {coverage['inspected_files']} source files; no configured risk indicators matched the inspected syntax/text."]
        reasons.append('Source-review priority only; not installation eligibility or a malware-free guarantee.')
        self.result['recommendation'] = dict(verdict=verdict, reasons=reasons)
        self.check('source_analysis', 'completed', 'Static syntax/declaration/text inspection only; no candidate imports or commands executed.')
        self.check('dynamic_execution', 'not_run', 'Candidate execution is prohibited; no sandbox test was performed.')
        self.check('analysis_scope', 'limited', 'Python AST aliases/arguments plus structured manifests and lexical non-Python inspection; no whole-program/cross-file dataflow or reachability proof.')
        self.check('malware_scanner', 'not_run', 'No antivirus engine or signature database was invoked.')
        self.check('vulnerability_database', 'not_run', 'No advisory database was queried; dependency names and declared versions are evidence only.')
        return _sanitize_tree(self.result, self.secrets)


def _source_line(text, value):
    for number, line in enumerate(text.splitlines(), 1):
        if str(value) in line:
            return number
    return 1


def _collect_secrets(audit, text):
    # Recognize JSON/Python quoted keys as well as assignment syntax; values
    # collected here are removed from every output field, including other files.
    key = r'\b(?:password|passwd|secret|api[_-]?key|access[_-]?token|token|authorization|[A-Z_]{0,64}(?:TOKEN|SECRET|PASSWORD|API_KEY))\b'
    quoted = r"(?i)[\"']?" + key + r"[\"']?\s*[=:]\s*[\"']([^\"'\r\n]+)[\"']"
    for match in re.finditer(quoted, text):
        audit.secrets.add(match.group(1))
    dotenv = r'(?im)^\s*' + key + r'\s*=\s*([^\s#]+)'
    for match in re.finditer(dotenv, text):
        audit.secrets.add(match.group(1).strip('"\''))
    for match in PRIVATE_KEY.finditer(text):
        audit.secrets.add(match.group())


class _Python(ast.NodeVisitor):
    """AST observations are syntax, including branches not known to be reachable."""
    def __init__(self, audit, path):
        self.audit, self.path = audit, path
        self.aliases = {}
        self.credentials = []
        self.network = []
        self.secret_variables = set()

    def name(self, node):
        if isinstance(node, ast.Name):
            return self.aliases.get(node.id, node.id)
        if isinstance(node, ast.Attribute):
            return self.name(node.value) + '.' + node.attr
        if isinstance(node, ast.Call):
            return self.name(node.func)
        return ''

    def detail(self, node):
        try:
            return ast.unparse(node)
        except (RecursionError, ValueError):
            return '[expression omitted]'

    def visit_Import(self, node):
        for alias in node.names:
            self.aliases[alias.asname or alias.name.split('.')[0]] = alias.name if alias.asname else alias.name.split('.')[0]

    def visit_ImportFrom(self, node):
        for alias in node.names:
            self.aliases[alias.asname or alias.name] = (node.module or '') + '.' + alias.name

    def visit_Expr(self, node):
        if not isinstance(node.value, ast.Constant) or not isinstance(node.value.value, str):
            self.generic_visit(node)

    def credential_source(self, node):
        name = self.name(node)
        detail = self.detail(node)
        return (name in ('os.getenv', 'os.environ.get', 'os.environ.__getitem__', 'keyring.get_password')
                or name.startswith('os.environ.')
                or isinstance(node, ast.Subscript) and self.name(node.value) == 'os.environ'
                or bool(re.search(r'[./](?:\.ssh|\.aws|\.env|credentials|id_rsa|id_ed25519)(?:[/\'".]|$)', detail)))

    def visit_Assign(self, node):
        if isinstance(node.value, ast.Call):
            constructor = self.name(node.value.func)
            if constructor in ('pathlib.Path', 'requests.Session', 'httpx.Client', 'httpx.AsyncClient', 'argparse.ArgumentParser'):
                for target in node.targets:
                    if isinstance(target, ast.Name):
                        self.aliases[target.id] = constructor
        if self.credential_source(node.value):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    self.secret_variables.add(target.id)
        for target in node.targets:
            if isinstance(target, ast.Name) and SECRET_NAME.search(target.id):
                if isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
                    self.audit.secrets.add(node.value.value)
                    self.secret_variables.add(target.id)
                    self.audit.indicator('embedded_credential', 'credentials', 'medium', self.path, node.lineno,
                                         'Credential-named variable contains a literal; value redacted.')
        self.generic_visit(node)

    def visit_If(self, node):
        if isinstance(node.test, ast.Compare) and isinstance(node.test.left, ast.Name) and node.test.left.id == '__name__':
            if any(isinstance(c, ast.Constant) and c.value == '__main__' for c in node.test.comparators):
                self.audit.add('entrypoints', dict(path=self.path, line=node.lineno, name='__main__', kind='python_main_guard'))
        self.generic_visit(node)

    def visit_Subscript(self, node):
        if self.name(node.value) == 'os.environ':
            self.credentials.append(node.lineno)
            self.audit.capability('credentials', 'Reads environment or credential material', self.path, node.lineno,
                                  'os.environ', self.detail(node))
        self.generic_visit(node)

    def visit_Constant(self, node):
        if isinstance(node.value, str):
            self.audit.endpoints(node.value, self.path, node.lineno, 'python_literal')

    def visit_Call(self, node):
        name = self.name(node.func)
        detail = self.detail(node)
        category = None
        if (name.startswith(('requests.', 'httpx.', 'aiohttp.', 'urllib.request.', 'socket.', 'http.client.'))
                and name.rsplit('.', 1)[-1] in ('get', 'post', 'put', 'delete', 'patch', 'request', 'urlopen', 'urlretrieve', 'connect', 'create_connection', 'send', 'sendall')):
            category = 'network'
            variables = {n.id for arg in list(node.args) + [k.value for k in node.keywords] for n in ast.walk(arg) if isinstance(n, ast.Name)}
            direct_source = any(self.credential_source(arg) for arg in list(node.args) + [k.value for k in node.keywords])
            self.network.append((node.lineno, bool(variables & self.secret_variables) or direct_source))
        elif name.startswith('subprocess.') or name in ('os.system', 'os.popen', 'os.execv', 'os.execve', 'os.spawnv', 'pty.spawn'):
            category = 'process'
            if name in ('os.system', 'os.popen') or any(k.arg == 'shell' and isinstance(k.value, ast.Constant) and k.value.value is True for k in node.keywords):
                self.audit.indicator('shell_execution', 'execution', 'medium', self.path, node.lineno,
                                     f'{name} requests shell command evaluation; inspect argument trust boundaries.')
        elif name in ('eval', 'exec', 'compile', '__import__', 'importlib.import_module', 'pickle.loads', 'pickle.load', 'marshal.loads'):
            category = 'dynamic_code'
            self.audit.indicator('dynamic_code', 'execution', 'medium', self.path, node.lineno,
                                 f'{name} can evaluate/load code or unsafe serialized objects; input origin needs review.')
        elif name in ('open', 'io.open', 'pathlib.Path.open'):
            mode = next((k.value for k in node.keywords if k.arg == 'mode'), node.args[1] if len(node.args) > 1 else ast.Constant(value='r'))
            category = 'filesystem_write' if isinstance(mode, ast.Constant) and isinstance(mode.value, str) and any(c in mode.value for c in 'wax+') else 'filesystem_read'
        elif name.startswith(('pathlib.Path.', 'os.', 'shutil.')):
            method = name.rsplit('.', 1)[-1]
            if method in ('read_text', 'read_bytes', 'listdir', 'walk', 'scandir'):
                category = 'filesystem_read'
            elif method in ('write_text', 'write_bytes', 'unlink', 'remove', 'rmdir', 'mkdir', 'makedirs', 'rename', 'replace', 'rmtree', 'copy', 'copyfile', 'move', 'chmod', 'chown', 'symlink'):
                category = 'filesystem_write'
        if self.credential_source(node):
            self.credentials.append(node.lineno)
            self.audit.capability('credentials', 'Reads environment or credential material', self.path, node.lineno, name, detail)
        if name == 'argparse.ArgumentParser.add_argument':
            self.audit.capability('interface', 'Declares command-line arguments', self.path, node.lineno, name, detail)
        if category:
            labels = {'network': 'Performs network requests', 'process': 'Starts external processes',
                      'dynamic_code': 'Loads or evaluates dynamic content', 'filesystem_read': 'Reads files or directories',
                      'filesystem_write': 'Creates, changes, or removes files'}
            self.audit.capability(category, labels[category], self.path, node.lineno, name, detail)
        if category in ('filesystem_write', 'process') and re.search(r'(?:crontab|systemctl|\.config/autostart|/etc/cron|\.bashrc|LaunchAgents|CurrentVersion\\Run)', detail, re.I):
            self.audit.indicator('persistence', 'persistence', 'high', self.path, node.lineno,
                                 'Write/process syntax references an autostart or scheduled-execution location.')
        self.generic_visit(node)

    def finish(self):
        for line, explicit_flow in self.network[:8]:
            if self.credentials or explicit_flow:
                self.audit.indicator('credential_network_combination', 'credentials', 'high' if explicit_flow else 'medium', self.path, line,
                                     'Credential-source variable is passed to a network call; verify destination and intended authorization.' if explicit_flow
                                     else 'Credential access and networking coexist in this file; data flow is not established.')


def _python(audit, path, text):
    try:
        tree = ast.parse(text, filename=path)
        visitor = _Python(audit, path)
        visitor.visit(tree)
        visitor.finish()
        audit.check('python_syntax', 'parsed', f'{path}: AST parsed; aliases resolved syntactically, not executed.')
    except (SyntaxError, ValueError, RecursionError, MemoryError) as exc:
        line = getattr(exc, 'lineno', None)
        audit.omit(path, f'Python syntax analysis unavailable at line {line or 1}; {type(exc).__name__}. No execution assumed.')


def _requirement(audit, value, ecosystem, path, line):
    # Preserve declaration, never resolve URLs or import a dependency.
    match = re.match(r'\s*([A-Za-z0-9_.-]+)(?:\[[^\]]*\])?\s*(.*)', str(value))
    if match:
        audit.dependency(match.group(1), match.group(2).strip() or '*', ecosystem, path, line)


def _structured_secrets(audit, value):
    """Collect decoded literals before rendering; escaped JSON/TOML is still data."""
    pending = [value]
    while pending:
        node = pending.pop()
        if isinstance(node, dict):
            for key, child in node.items():
                if SECRET_NAME.search(str(key)) and isinstance(child, str) and child:
                    audit.secrets.add(child)
                if isinstance(child, (dict, list)):
                    pending.append(child)
        elif isinstance(node, list):
            pending.extend(child for child in node if isinstance(child, (dict, list)))


def _manifest(audit, path, text, kind):
    try:
        if kind == 'npm_manifest':
            data = json.loads(text)
            if not isinstance(data, dict):
                raise ValueError('manifest must be an object')
            _structured_secrets(audit, data)
            if isinstance(data.get('license'),str):
                audit.add('licenses',dict(path=path,identifier=data['license']))
            for group in ('dependencies', 'devDependencies', 'optionalDependencies', 'peerDependencies'):
                for name, version in (data.get(group) or {}).items():
                    audit.dependency(name, version, 'npm:' + group, path, _source_line(text, json.dumps(name)))
            for name, command in (data.get('scripts') or {}).items():
                line = _source_line(text, json.dumps(name))
                audit.add('entrypoints', dict(path=path, line=line, name=name, kind='npm_script'))
                audit.capability('declared_command', 'Declares package commands', path, line, 'scripts.' + name, str(command))
                _text_line(audit, path, line, str(command), 'manifest_script')
                if name in ('preinstall', 'install', 'postinstall', 'prepare', 'prepublish', 'prepublishOnly'):
                    audit.indicator('install_hook', 'execution', 'medium', path, line,
                                    f'{name} lifecycle hook declares: {command}')
            bins = data.get('bin', {})
            if isinstance(bins, str):
                bins = {data.get('name', 'package'): bins}
            if isinstance(bins, dict):
                for name, target in bins.items():
                    audit.add('entrypoints', dict(path=path, line=_source_line(text, 'bin'), name=name, kind='npm_bin:' + str(target)))
            for runtime, version in (data.get('engines') or {}).items():
                audit.check('declared_runtime', 'declared', f'{path}: {runtime} {version}')
        elif kind == 'requirements':
            for line, value in enumerate(text.splitlines(), 1):
                value = value.strip()
                if not value or value.startswith('#'):
                    continue
                if value.startswith('-'):
                    audit.capability('dependency_source', 'Changes dependency installation sources/options', path, line, 'pip', value)
                    audit.indicator('dependency_option', 'supply_chain', 'medium', path, line, 'Dependency file includes an installer option/include; target was not followed.')
                else:
                    _requirement(audit, value, 'pypi', path, line)
                    audit.endpoints(value, path, line, 'dependency_declaration')
        elif kind == 'toml':
            if tomllib is None:
                audit.omit(path, 'TOML parser unavailable; requires Python 3.11+ for structured manifest inspection.')
                return
            data = tomllib.loads(text)
            _structured_secrets(audit, data)
            project = data.get('project', {})
            for dependency in project.get('dependencies', []):
                _requirement(audit, dependency, 'pypi', path, _source_line(text, dependency))
            for group, dependencies in project.get('optional-dependencies', {}).items():
                for dependency in dependencies:
                    _requirement(audit, dependency, 'pypi:' + group, path, _source_line(text, dependency))
            for name, target in project.get('scripts', {}).items():
                audit.add('entrypoints', dict(path=path, line=_source_line(text, name), name=name, kind='python_script:' + str(target)))
            if project.get('requires-python'):
                audit.check('declared_runtime', 'declared', f'{path}: Python {project["requires-python"]}')
            poetry = data.get('tool', {}).get('poetry', {})
            for name, version in poetry.get('dependencies', {}).items():
                if name == 'python':
                    audit.check('declared_runtime', 'declared', f'{path}: Python {version}')
                else:
                    audit.dependency(name, version, 'poetry', path, _source_line(text, name))
            for name, version in data.get('dependencies', {}).items():
                audit.dependency(name, version if not isinstance(version, dict) else version.get('version', str(version)), 'cargo' if path.endswith('Cargo.toml') else 'toml', path, _source_line(text, name))
            if data.get('build-system'):
                build = data['build-system']
                for dependency in build.get('requires', []):
                    _requirement(audit, dependency, 'python_build', path, _source_line(text, dependency))
                audit.capability('build_backend', 'Declares a build backend', path, _source_line(text, 'build-backend'), 'build-system', str(build.get('build-backend', 'unspecified')))
    except (ValueError, TypeError, AttributeError, RecursionError) as exc:
        audit.omit(path, f'Structured manifest analysis unavailable: {type(exc).__name__}; declaration may be malformed.')


def _text_line(audit, path, number, line, kind):
    """Lexical indicators are labeled as textual, never executed/syntax-validated."""
    line = line.strip()
    if not line or line.startswith(('#', '//', '*', '<!--')):
        return
    audit.endpoints(line, path, number, kind + '_text')
    rules = [
        ('network', 'Contains network operation text', r'\b(?:curl|wget|fetch|axios|Invoke-WebRequest)\b|https?://', 'network'),
        ('process', 'Contains process/command operation text', r'\b(?:execSync|spawnSync|spawn|execFile|exec|child_process|subprocess|os\.system|subprocess\.run)\s*[.(]|^\s*(?:RUN|CMD|ENTRYPOINT)\b', 'execution'),
        ('filesystem_write', 'Contains filesystem mutation text', r'\b(?:writeFile|writeFileSync|unlink|rm\s+-|chmod|chown|mkdir|write_text|write_bytes)\b', 'filesystem'),
        ('filesystem_read', 'Contains filesystem read text', r'\b(?:readFile|readFileSync|read_text|read_bytes|Get-Content)\b', 'filesystem'),
        ('credentials', 'Contains environment/credential access text', r'process\.env|\bos\.environ|\bos\.getenv|\$\{?(?:[A-Z_]*(?:TOKEN|SECRET|PASSWORD|API_KEY))\b|(?:~/|\$HOME/|/root/)\.(?:ssh|aws)', 'credentials'),
    ]
    for category, label, pattern, _ in rules:
        if re.search(pattern, line, re.I):
            audit.capability(category, label, path, number, kind + ':textual', line)
    if re.search(r'\b(?:curl|wget)\b.*\|\s*(?:(?:sudo|env)\s+)?(?:ba)?sh\b|\b(?:iex|Invoke-Expression)\b', line, re.I):
        audit.indicator('download_execute', 'execution', 'high', path, number,
                        f'Textual download-to-interpreter/evaluation pattern ({kind}); inspect source: {line}')
    if re.search(r'\b(?:curl|wget|fetch|axios)\b', line, re.I) and re.search(r'process\.env|\$\{?[A-Z_]*(?:TOKEN|SECRET|PASSWORD|API_KEY)\b', line):
        audit.indicator('credential_network_text', 'credentials', 'high', path, number,
                        f'Network and credential-source text occur on the same line ({kind}); dataflow/authorization needs review: {line}')
    if re.search(r'\b(?:eval|Function)\s*\(|(?:base64\s+-d|frombase64string|atob\s*\()', line, re.I):
        audit.indicator('dynamic_code_text', 'execution', 'medium', path, number,
                        f'Textual decoding/dynamic-evaluation pattern ({kind}); not executed: {line}')
    if re.search(r'(?:crontab|systemctl\s+enable|/etc/cron|\.config/autostart|LaunchAgents|CurrentVersion\\Run)', line, re.I):
        audit.indicator('persistence_text', 'persistence', 'medium', path, number,
                        f'Text references scheduled execution/autostart ({kind}): {line}')
    if re.search(r'(?:ignore|override|disregard)\s+(?:all\s+)?(?:previous|prior|system|safety|security)\s+(?:instructions|rules|prompts)|(?:disable|bypass)\s+(?:quarantine|sandbox|security|protections)', line, re.I):
        audit.indicator('instruction_override', 'instructions', 'medium', path, number,
                        f'Instruction-override/protection-bypass text ({kind}); treat as untrusted content: {line}')
    if re.search(r'(?:--privileged|docker\.sock|network_mode:\s*host|privileged:\s*true)', line, re.I):
        audit.indicator('elevated_container', 'permissions', 'high', path, number,
                        f'Configuration text requests host/elevated container access: {line}')


def _text(audit, path, text, kind):
    for number, line in enumerate(text.splitlines(), 1):
        _text_line(audit, path, number, line, kind)
        if kind == 'documentation':
            if re.match(r'^(?:description|name|allowed-tools|permissions)\s*:', line, re.I):
                label = 'Declares skill purpose or requested tools/permissions'
                audit.capability('declared_skill', label, path, number, 'documentation:declaration', line)
            elif line.startswith('# ') and len(line) < 200:
                audit.capability('declared_purpose', 'Declares document/tool purpose', path, number, 'documentation:heading', line[2:])
        if kind == 'docker' and re.match(r'^(?:FROM|USER|EXPOSE|ENTRYPOINT|CMD)\s', line, re.I):
            audit.capability('container', 'Declares container runtime/configuration', path, number, 'docker:declaration', line)
            if re.match(r'^USER\s+(?:root|0)\b', line, re.I):
                audit.indicator('root_container', 'permissions', 'medium', path, number, 'Container declares root execution.')
        if number == 1 and line.startswith('#!'):
            audit.add('entrypoints', dict(path=path, line=number, name=PurePosixPath(path).name, kind='shebang:' + line[2:]))


def _license(audit, path, text):
    identifier = None
    spdx = re.search(r'SPDX-License-Identifier:\s*([A-Za-z0-9.+() -]{1,100})', text)
    if spdx:
        identifier = spdx.group(1).strip()
    elif re.search(r'\bMIT License\b|Permission is hereby granted, free of charge', text, re.I):
        identifier = 'MIT'
    elif re.search(r'Apache License(?:,?\s*Version)?\s*2\.0', text, re.I):
        identifier = 'Apache-2.0'
    elif re.search(r'GNU GENERAL PUBLIC LICENSE\s*Version 3', text, re.I):
        identifier = 'GPL-3.0 (exact variant unverified)'
    if identifier:
        audit.add('licenses', dict(path=path, identifier=identifier))


def audit_files(files, provenance=None):
    """Inspect a filename -> bytes mapping. No imports, execution, network or writes.

    All source-derived strings are redacted at the output boundary. Facts describe
    bounded static source inspection, never a malware-free or installable verdict.
    """
    audit = _Audit()
    selection = (provenance or {}).get('selection')
    if selection:
        audit.result['coverage']['acquisition'] = selection
        audit.omit('[GitHub source selection]',
                   f"Selected {selection['received_files']} source files; {selection['omitted_files']} scoped resources and {selection['excluded_repository_files']} repository files were not received. This is not a full repository audit.")
    audit.result['coverage']['total_files'] = len(files)
    audit.result['coverage']['total_bytes'] = sum(len(data) for data in files.values() if isinstance(data, bytes))
    expanded = 0
    for index, (path, data) in enumerate(files.items()):
        path = str(path)
        if index >= MAX_MEMBERS:
            audit.omit(path, f'File count limit {MAX_MEMBERS}; source not inspected.')
            continue
        if not isinstance(data, bytes):
            audit.omit(path, 'Input member is not bytes; source not inspected.')
            continue
        kind = _kind(path, data)
        inventory = dict(path=path, bytes=len(data), sha256=hashlib.sha256(data).hexdigest(), kind=kind, lines=None)
        audit.add('inventory', inventory)
        expanded += len(data)
        if len(data) > MAX_MEMBER or expanded > MAX_EXPANDED:
            audit.omit(path, 'Member/expanded byte budget exceeded; source not inspected.')
            continue
        if kind == 'binary':
            audit.omit(path, 'Opaque/binary bytes; not disassembled or executed.')
            continue
        truncated = len(data) > MAX_TEXT
        if truncated:
            audit.omit(path, f'Text truncated after {MAX_TEXT} bytes; remainder not inspected.')
        try:
            if kind == 'python':
                encoding, _ = tokenize.detect_encoding(io.BytesIO(data[:MAX_TEXT]).readline)
            else:
                encoding = 'utf-8-sig'
            # bytes.decode rejects transform codecs (rot13/base64/hex) as non-text.
            b''.decode(encoding)
            decoder = codecs.getincrementaldecoder(encoding)(errors='strict')
            text = decoder.decode(data[:MAX_TEXT], final=not truncated)
            if not isinstance(text, str):
                raise ValueError('Non-text Python source encoding')
        except (UnicodeError, SyntaxError, LookupError, TypeError, ValueError):
            audit.omit(path, 'Unsupported text encoding/opaque binary; source not inspected.')
            continue
        inventory['lines'] = len(text.splitlines())
        audit.result['coverage']['inspected_files'] += 1
        _collect_secrets(audit, text)
        if kind == 'python':
            _python(audit, path, text)
        elif kind in ('npm_manifest', 'requirements', 'toml'):
            _manifest(audit, path, text, kind)
        else:
            _text(audit, path, text, kind)
        _license(audit, path, text)
    return audit.finish()


def _safe_name(name):
    if not name or '\\' in name or CONTROL.search(name) or name.startswith('/') or re.match(r'^[A-Za-z]:', name):
        return False
    parts = name.rstrip('/').split('/')
    return all(part not in ('', '.', '..') for part in parts)


def read_package(data, name):
    """Read one bounded file or ZIP bytes in memory; never extract to disk."""
    if len(data) > MAX_INPUT:
        raise ValueError('Input exceeds 5 MiB limit.')
    is_zip = zipfile.is_zipfile(io.BytesIO(data))
    if not is_zip:
        if str(name).lower().endswith(ARCHIVE_SUFFIXES) or data.startswith((b'PK\x03\x04', b'\x1f\x8b', b'7z\xbc\xaf', b'Rar!')):
            raise ValueError('Unsupported or invalid archive; provide a valid ZIP or a source file.')
        if len(data) > MAX_MEMBER:
            raise ValueError('Source file exceeds 512 KiB member limit.')
        return {Path(name).name: data}
    try:
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            members = archive.infolist()
            if len(members) > MAX_MEMBERS:
                raise ValueError('ZIP exceeds 512-member limit.')
            result, seen, total = {}, set(), 0
            for member in members:
                name = member.filename
                if not _safe_name(name):
                    raise ValueError('ZIP contains an unsafe path.')
                normalized = name.rstrip('/')
                if normalized in seen:
                    raise ValueError('ZIP contains duplicate paths.')
                seen.add(normalized)
                mode = member.external_attr >> 16
                if stat.S_ISLNK(mode) or (stat.S_IFMT(mode) not in (0, stat.S_IFREG, stat.S_IFDIR)):
                    raise ValueError('ZIP contains a link or special file.')
                if member.flag_bits & 1:
                    raise ValueError('Encrypted ZIP members are unsupported.')
                if member.is_dir():
                    continue
                if member.file_size > MAX_MEMBER:
                    raise ValueError('ZIP member exceeds 512 KiB limit.')
                total += member.file_size
                if total > MAX_EXPANDED:
                    raise ValueError('ZIP exceeds 8 MiB expanded limit.')
                if member.file_size / max(member.compress_size, 1) > MAX_RATIO:
                    raise ValueError('ZIP decompression ratio exceeds 100:1 limit.')
                with archive.open(member) as source:
                    content = source.read(MAX_MEMBER + 1)
                if len(content) != member.file_size or len(content) > MAX_MEMBER:
                    raise ValueError('ZIP member size mismatch.')
                if name.lower().endswith(ARCHIVE_SUFFIXES) or zipfile.is_zipfile(io.BytesIO(content)) or content.startswith((b'PK\x03\x04', b'\x1f\x8b', b'7z\xbc\xaf', b'Rar!')):
                    raise ValueError('Nested archives are not inspected; provide the inner source separately.')
                result[name] = content
            return result
    except (zipfile.BadZipFile, NotImplementedError, RuntimeError, EOFError, zlib.error) as exc:
        raise ValueError('ZIP could not be read safely.') from exc


